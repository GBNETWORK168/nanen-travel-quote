/** 只給日期：頭尾都算（迄日减起日＋1）。 */
function guoluDaysInclusive(startYMD, endYMD) {
  const s = parseYMD(startYMD);
  const e = parseYMD(endYMD);
  if (!s || !e) return { error: '請完整填寫起迄日期' };
  if (e < s) return { error: '迄日不可早於起日' };
  const days = Math.round((e - s) / 86400000) + 1;
  return { days, mode: 'dates', label: '日期頭尾都算' };
}

/** 有時刻：按時數，未滿一日以一日計（剛好滿 N 個 24 小時＝N 天）。 */
function guoluDaysByHours(startYMD, startHM, endYMD, endHM) {
  const s = parseYMDHM(startYMD, startHM);
  const e = parseYMDHM(endYMD, endHM);
  if (!s || !e) return { error: '已填時刻時，起迄日期與時刻都要完整' };
  if (e <= s) return { error: '迄日時刻必須晚於起日時刻' };
  const hours = (e - s) / 3600000;
  const days = Math.ceil(hours / 24 - 1e-9);
  const hLabel = formatHours(hours);
  return { days, hours, mode: 'hours', label: '已輸入時刻，按時數算整天（' + hLabel + '＝' + days + '天）' };
}

function parseYMD(ymd) {
  if (!ymd || !/^\d{4}-\d{2}-\d{2}$/.test(ymd)) return null;
  const [y, m, d] = ymd.split('-').map(Number);
  const dt = new Date(y, m - 1, d, 0, 0, 0, 0);
  if (dt.getFullYear() !== y || dt.getMonth() !== m - 1 || dt.getDate() !== d) return null;
  return dt;
}

function parseYMDHM(ymd, hm) {
  if (!hm || !/^\d{2}:\d{2}$/.test(hm)) return null;
  const date = parseYMD(ymd);
  if (!date) return null;
  const [hh, mm] = hm.split(':').map(Number);
  if (hh > 23 || mm > 59) return null;
  return new Date(date.getFullYear(), date.getMonth(), date.getDate(), hh, mm, 0, 0);
}

function formatHours(hours) {
  const totalMin = Math.round(hours * 60);
  const h = Math.floor(totalMin / 60);
  const m = totalMin % 60;
  if (m === 0) return h + '小時';
  return h + '小時' + m + '分';
}

function guoluPremium(planId, days) {
  const g = window.GUOLU;
  if (!Number.isInteger(days) || days < g.days_min || days > g.days_max) {
    return { error: 'DM僅列1～20日，此天數請向業務人員洽詢，不內插' };
  }
  const row = g.rates[planId];
  if (!row) return { error: '找不到此計畫' };
  return { premium: row[days - 1] };
}

function guoluPlan(planId) {
  return (window.GUOLU.plans || []).find(function (p) { return p.id === planId; }) || null;
}

function guoluAgeOk(plan, age) {
  if (age === null || age === undefined || age === '') return { ok: true, checked: false };
  const n = Number(age);
  if (!Number.isInteger(n) || n < 0 || n > 120) return { ok: false, checked: true, error: '足歲請填 0～120 的整數' };
  if (plan.age_min == null && plan.age_max != null) {
    // 兒童：未滿15足歲 → 0～14
    if (n <= plan.age_max) return { ok: true, checked: true };
    return { ok: false, checked: true, error: '此年齡不在「' + plan.name + '」可投保年齡（' + plan.age + '）內' };
  }
  if (n >= plan.age_min && n <= plan.age_max) return { ok: true, checked: true };
  return { ok: false, checked: true, error: '此年齡不在「' + plan.name + '」可投保年齡（' + plan.age + '）內' };
}

